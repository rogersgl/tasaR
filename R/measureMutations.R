findAIDtargets <- function(settings) {
  if (class(settings) == "tas.object.settings") {
    config <- getSettings(settings)
  } else {
    config <- settings
  }
  if (class(config) != "list") {
    stop("settings must be a tas.object.settings object or a list")
  }

  AID.Motifs <- c("WRCY","RGYW","WRCH","DGYW")
  # aid[AID.Motifs] <- S4Vectors::lapply(AID.Motifs, function(x){

  aid <- S4Vectors::lapply(config$ReferenceSequence, function(seq) {
    t <- rbindlist(S4Vectors::lapply(AID.Motifs, function(m) {
        pat.views <- Biostrings::matchPattern(m, Biostrings::DNAString(seq), fixed = FALSE)
        s <- Biostrings::start(pat.views)
        e <- Biostrings::end(pat.views)

        if (m == "WRCY" | m == "WRCH"){
          cyt <- e-1
        }
        if (m == "RGYW" | m == "DGYW"){
          cyt <- e-2
        }
        data.frame(Motif=rep(m, length(pat.views)), Start=s, End=e, Cytosine=cyt)
      }))

      y.df <- as.data.frame(rbind(t[t$Motif == "WRCY",], t[t$Motif == "RGYW"]))
      y.df <- y.df[order(y.df$Start),]
      h.df <- as.data.frame(rbind(t[t$Motif == "WRCH",], t[t$Motif == "DGYW"]))
      h.df <- h.df[order(h.df$Start),]

      list(WRCH = h.df, WRCY = y.df)
    })

  return(aid) # new structure list(list(WRCH, WRCY), ...)
}


getAntibodyCoordinates <- function(abr) {
  out <- list(length(abr))
  for (i in seq_along(abr)[-length(abr)]) {
    out[[i]] <- abr[i]:(abr[i+1] - 1)
  }
  names(out) <- stringr::str_remove(names(abr), "Start")[-length(abr)]
  return(out)
}


