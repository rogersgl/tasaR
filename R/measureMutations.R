  ################################################################
  # TODO: FIX PROBLEM HERE
  # failing on heterozygous input test with invalid times t$count
  # I think this is because the sequenceTable is combined from separate lists
  # so its too long relative to each individual msa.dna to replicate
  #
  # Not sure how to fix right now, need a tas.sequences output that
  # carries over the count statistics while keeping separated with the
  # separate reference sequence lists.
  #######################################
  t <- data.table(Count = getSequenceTable(sequence.table)$Count,
                  RefIdx = getSequenceSupplemental(sequence.table)$RefIdx
                  )
  msa.dna <- getDNAmsa(sequence.table)

  msa.cm.list <- lapply(seq_along(msa.dna), function(x) {
    mat <- Biostrings::as.matrix(msa.dna[[x]])
    wt.mat <- mat[1,]
    msa.mat <- mat[2:nrow(msa.dna[[x]]), ,drop = FALSE]
    msa.mat.all <- msa.mat[rep.int(seq_len(nrow(msa.mat)), t$Count[t$RefIdx == x]), , drop = FALSE]
    msa.cm <- Biostrings::consensusMatrix(msa.mat.all)
    if (all(c("-", "A", "C", "G", "T") %in% rownames(msa.cm))) {
      msa.cm <- msa.cm[c("-", "A", "C", "G", "T"),]
    } else if (all(c("A", "C", "G", "T") %in% rownames(msa.cm)) && !"-" %in% rownames(msa.cm)){
      msa.cm <- rbind(matrix(0, ncol = ncol(msa.cm), dimnames = list("-", NULL)), msa.cm)
    }
    wt.cm <- Biostrings::consensusMatrix(Biostrings::DNAStringSet(stringr::str_flatten(wt.mat)))[c("-", "A", "C", "G", "T"),]
    msa.cm[wt.cm == 1] <- 0
    cm.colnames <- character(ncol(msa.cm))
    pos <- 0
    # TODO: evaluate speed and determine if this R for loop is fast enough, or if it needs to be farmed out to C
    for (i in seq_along(cm.colnames)) {
      if (wt.mat[i] != "-" && pos %% 1 == 0) {
        pos <- pos + 1
      } else if (wt.mat[i] == "-" && pos %% 1 == 0){
        pos <- pos + 0.5
      } else if (wt.mat[i] != "-" && pos %% 1 == 0.5){
        pos <- pos + 0.5
      }

      # do nothing for (wt.cm[i] == "-" && pos %% 1 == 0.5)
      # give same number for consecutive insertions since they're still between the same reference base #'s

      cm.colnames[i] <- pos
    }
    colnames(msa.cm) <- cm.colnames
    return(msa.cm)
  })

  # deal with edge case of different sized matrices if different max insertion
  # size for different ref sequences
  list.colnames <- lapply(msa.cm.list, colnames)
  if (length(unique(list.colnames)) > 1) {
    col.count <- table(unlist(list.colnames))
    col.unique <- names(col.count[col.count < length(list.colnames)])
    for (i in seq_along(list.colnames)) {
      miss <- !(col.unique %in% list.colnames[[i]])
      if (any(miss)) {
        msa.cm.list[[i]] <- cbind(msa.cm.list[[i]], matrix(0,
                                                           nrow = nrow(msa.cm.list[[i]]),
                                                           ncol = length(col.unique[miss]),
                                                           dimnames = list(NULL, col.unique[miss]))
                                  )[,stringr::str_sort(colnames(msa.cm.list[[i]]), numeric = TRUE)]
      }
    }
  }
  msa.cm <- Reduce("+", msa.cm.list)
  msa.cm <- msa.cm/sum(t$Count)*100
  all.mut <- data.frame(Position = as.numeric(colnames(msa.cm)),
                        MutationFrequency = colSums(msa.cm), row.names = NULL)
  output <- new("tas.mutations")
  output@DNA$AllMutations <- all.mut
  return(output)
}



